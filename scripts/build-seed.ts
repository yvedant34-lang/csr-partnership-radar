// Generates seed/seed_live.sql from seed/csr_leads_live.csv (real rows, verified 12 Oct 2026).
// Run: node scripts/build-seed.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseCsv } from "../lib/csv.ts";

const rows = parseCsv(readFileSync("seed/csr_leads_live.csv", "utf8"));
const config = JSON.parse(readFileSync("seed/radar_config.json", "utf8"));
for (const k of Object.keys(config)) if (k.startsWith("_")) delete config[k];

const q = (v: string | null) => (v == null || v === "" ? "null" : `'${v.replace(/'/g, "''")}'`);
const num = (v: string) => (v === "" ? "null" : String(Number(v)));
const bool = (v: string) => (v === "True" ? "true" : "false");
const arr = (v: string) => `'{${v ? v.split(";").map((s) => `"${s}"`).join(",") : ""}}'`;

const cols = [
  "lead_id", "company_name", "industry", "csr_focus_area", "city", "state", "geo_scope", "poc_name", "poc_designation",
  "poc_email", "poc_phone", "poc_linkedin", "contact_source", "source_type", "source_name", "post_link", "signal_type",
  "budget_inr_cr", "budget_basis", "posted_at", "posted_time_precision", "implementation_partner", "beneficiaries",
  "summary", "why_now", "priority_score", "probability_of_conversion_pct", "tier", "recommended_action",
  "pipeline_stage", "owner", "is_synthetic", "verified_at", "proven_funder", "score_signal", "score_recency",
  "score_sector_fit", "score_geo_fit", "score_budget_fit", "flags", "hot_gate_fails",
];
const numeric = new Set(["budget_inr_cr", "priority_score", "probability_of_conversion_pct", "score_signal",
  "score_recency", "score_sector_fit", "score_geo_fit", "score_budget_fit"]);
const bools = new Set(["is_synthetic", "proven_funder"]);
const arrays = new Set(["flags", "hot_gate_fails"]);

const values = rows.map((r) => {
  const v = cols.map((c) => (numeric.has(c) ? num(r[c]) : bools.has(c) ? bool(r[c]) : arrays.has(c) ? arr(r[c]) : q(r[c])));
  // Zeta's programme states come from the source article (Bengaluru, Mumbai centres + Hyderabad).
  const programme = r.lead_id === "LIVE-001" ? `'{"Telangana","Karnataka","Maharashtra"}'` : "'{}'";
  return `  (${[...v, programme, "'high'", "'2026-10-12T18:00:00+05:30'"].join(", ")})`;
});

const LUSHA = "seed/private/lusha_contacts.json";
const lusha = existsSync(LUSHA) ? JSON.parse(readFileSync(LUSHA, "utf8")) : { contacts: [], found_at: null };
const contactValues = lusha.contacts.map((c: Record<string, string | string[] | null>) =>
  `  (${[q(c.lead_id as string), q(c.match as string), q(c.lusha_id as string), q(c.name as string), q(c.title as string),
    q(c.city as string), q(c.state as string), q(c.linkedin as string), q((c.email as string) ?? null), q((c.revealed_at as string) ?? null),
    `'{${(c.can_reveal as string[]).map((f) => `"${f}"`).join(",")}}'`, q(lusha.found_at)].join(", ")})`);

const lushaSql = `-- Lusha candidates (search only, nothing revealed). See seed/lusha_contacts.json.
insert into lead_contacts (lead_id, source, match, lusha_id, name, title, city, state, linkedin, email, revealed_at, can_reveal, found_at)
select l.id, 'lusha', v.match, v.lusha_id, v.name, v.title, v.city, v.state, v.linkedin, v.email, v.revealed_at::timestamptz, v.can_reveal::text[], v.found_at::timestamptz
from (values
${contactValues.join(",\n")}
) as v(lead_ref, match, lusha_id, name, title, city, state, linkedin, email, revealed_at, can_reveal, found_at)
join leads l on l.lead_id = v.lead_ref
on conflict (lead_id, lusha_id) do nothing;

insert into lusha_spend (action, credits, note, spent_at)
select 'search', 2, 'CSR contacts at the 15 seed companies', '2026-10-12T17:30:00+05:30'
where not exists (select 1 from lusha_spend where action = 'search');
insert into lusha_spend (action, credits, note, spent_at)
select 'reveal_email', 3, '3 CSR head emails', '2026-10-12T18:05:00+05:30'
where not exists (select 1 from lusha_spend where action = 'reveal_email');
`;

const sql = `-- Generated by scripts/build-seed.ts from seed/csr_leads_live.csv. Do not edit by hand.
-- Real leads, verified 12 Oct 2026. Scores are recomputed by the app on every ingest run.

insert into radar_config (id, config) values (1, ${q(JSON.stringify(config))}::jsonb)
on conflict (id) do update set config = excluded.config, updated_at = now();

insert into leads (${cols.join(", ")}, programme_states, extraction_confidence, scored_at) values
${values.join(",\n")}
on conflict (lead_id) do nothing;

-- Every lead starts in "new": one stage event at the time it was found.
insert into lead_stage_events (lead_id, from_stage, to_stage, changed_at)
select l.id, null, 'new', l.verified_at::timestamptz + interval '9 hours'
from leads l
where l.lead_id like 'LIVE-%'
  and not exists (select 1 from lead_stage_events e where e.lead_id = l.id);

-- Contacts named in the source article.
insert into lead_contacts (lead_id, source, name, title)
select l.id, 'source_text', l.poc_name, l.poc_designation
from leads l
where l.lead_id like 'LIVE-%' and l.poc_name is not null
  and not exists (select 1 from lead_contacts c where c.lead_id = l.id and c.source = 'source_text');

`;
writeFileSync("seed/seed_live.sql", sql);

// Lusha contacts are personal data from a paid database: written to a gitignored file only.
if (lusha.contacts.length) {
  mkdirSync("seed/private", { recursive: true });
  writeFileSync("seed/private/seed_lusha.sql", `-- Generated by scripts/build-seed.ts. Gitignored: contains Lusha contact records.\n${lushaSql}`);
  console.log(`seed/private/seed_lusha.sql: ${lusha.contacts.length} Lusha contacts`);
}
console.log(`seed/seed_live.sql: ${rows.length} leads`);
